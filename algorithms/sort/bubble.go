// сохранён: алгоритм — in-place, по возрастанию, с досрочным выходом.
//
// Единственная копия цикла алгоритма живёт в BubbleSortWithEmitter
// (bubble_events.go): тихий режим — это тот же проход по массиву с nil
// эмиттером, и emit внутри просто молчит.
func BubbleSort(nums []int) {
	BubbleSortWithEmitter(nums, nil)
}
