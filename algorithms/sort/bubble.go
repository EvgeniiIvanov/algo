// Пакет sort — простые сортировки целочисленного слайса: библиотечный слой
// без знаний о визуализации. Каждый алгоритм работает в тихом режиме
// (обычная функция) и опционально стреляет типизированными событиями шагов
// в общий Emitter (ADR-0001; события bubble sort см. bubble_events.go).
package sort

// BubbleSort — bubble sort по возрастанию: тихий режим, сортировка идёт
// на месте, без событий и без копий (ADR-0001). Учебный черновик пользователя
// сохранён — агент добавил только комментарии и пакетный док.
//
// Идея: проходы слева направо сравнивают соседние элементы; каждая строго
// убывающая пара (nums[j] > nums[j+1]) меняется местами, и максимум остатка
// «всплывает» в конец. Равные соседи не обмениваются (строгое «больше»),
// поэтому сортировка устойчива. После прохода без обменов массив уже
// упорядочен — работа завершается досрочно.
func BubbleSort(nums []int) {
	n := len(nums)
	for i := 0; i < n-1; i++ {
		swapped := false
		for j := 0; j < n-1-i; j++ {
			if nums[j] > nums[j+1] {
				nums[j], nums[j+1] = nums[j+1], nums[j]
				swapped = true
			}
		}
		if !swapped {
			break
		}
	}
}
