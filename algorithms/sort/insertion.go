package sort

// InsertionSort — insertion sort по возрастанию: тихий режим, сортировка
// идёт на месте, без событий и без копий (ADR-0001). Учебный черновик
// пользователя сохранён: классический устойчивый вариант — ключ удерживается
// вне массива, отсортированный префикс сканируется справа налево, строго
// большие ключа значения сдвигаются вправо, затем ключ вставляется
// в освободившуюся позицию.
//
// Единственная копия цикла алгоритма живёт в InsertionSortWithEmitter
// (insertion_events.go): тихий режим — это тот же проход по массиву с nil
// эмиттером; эмиссия охраняется проверкой em != nil на месте вызова,
// поэтому до преобразования события в интерфейс (и до вызова эмиссии)
// в тихом режиме дело не доходит — аллокаций нет.
func InsertionSort(nums []int) {
	InsertionSortWithEmitter(nums, nil)
}
