package sort

// MergeSort — merge sort по возрастанию: тихий режим, сортировка идёт
// на месте с точки зрения вызывающего кода, без событий. Вспомогательная
// память — O(n): слияние аккумулирует результат в буфере, затем переносит
// его обратно во входной слайс.
//
// Единственная копия цикла алгоритма живёт в MergeSortWithEmitter
// (merge_events.go): тихий режим — тот же рекурсивный спуск с nil
// эмиттером, и emit внутри просто молчит.
//
// Идея (учебный черновик пользователя, Ч2.5): top-down рекурсия делит
// диапазон пополам (hi — исключительная граница), сортирует половины
// и сливает их через буфер; при равных значениях первым берётся элемент
// левой половины — слияние устойчивое.
func MergeSort(nums []int) {
	MergeSortWithEmitter(nums, nil)
}
