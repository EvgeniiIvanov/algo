package sort

// QuickSort — быстрая сортировка по возрастанию: тихий режим, сортировка
// идёт на месте с точки зрения вызывающего кода, без событий. Вариант —
// Lomuto: pivot — последний элемент диапазона, строго меньшие значения
// переносятся влево, затем pivot занимает финальную позицию. Вариант
// неустойчив; среднее время O(n log n), худшее O(n²) — в частности на
// уже упорядоченных входах при выбранном pivot.
//
// Единственная копия цикла алгоритма живёт в QuickSortWithEmitter
// (quicksort_events.go): тихий режим — та же рекурсия с nil эмиттером,
// и emit внутри просто молчит.
//
// Идея (учебный черновик пользователя, Ч2.5): рекурсия по включительному
// диапазону lo..hi; если lo >= hi — отрезок пуст или одноэлементный,
// сортировать его не нужно. Partition выбирает pivot nums[hi], строго
// меньшие значения переносит в левую часть (Lomuto: граница i растёт,
// обмен носит строго меньшее влево) и ставит pivot на финальную позицию
// i+1; затем рекурсия сортирует [lo..p-1] и [p+1..hi].
func QuickSort(nums []int) {
	QuickSortWithEmitter(nums, nil)
}
