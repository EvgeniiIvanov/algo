package structures

// HashTable — учебная хеш-таблица с фиксированным числом корзин (buckets) и
// разрешением коллизий методом цепочек: каждая корзина хранит односвязную
// цепочку записей «ключ — значение» (см. hashEntry). Таблица не растёт и не
// делает rehash — число корзин задаётся при создании и дальше не меняется,
// поэтому вставка, поиск и удаление трогают только одну корзину, а цену
// коллизий видно прямо по длине цепочки. Неизменность числа корзин ещё и
// делает хеширование детерминированным: при 5 корзинах ключи 1, 6 и 11
// всегда попадут в корзину 1.
type HashTable struct {
	buckets []*hashEntry // buckets[i] — голова цепочки корзины i (nil — корзина пуста)
	size    int          // сколько записей хранится во всей таблице
}

// hashEntry — одна запись цепочки корзины: пара «ключ — значение» и связь
// со следующей записью той же корзины. Отдельный тип (а не переиспользование
// node односвязного списка) выбран осознанно: node хранит только int-значение,
// а запись обязана нести и ключ, и значение — по ключу идёт поиск, и делать
// значение-ключом внутри общего узла — значило бы спутать две разные
// абстракции ради экономии одного маленького типа.
type hashEntry struct {
	key   int
	value int
	next  *hashEntry
}

// NewHashTable создаёт пустую таблицу с заданным числом корзин. Число
// корзин должно быть положительным: ноль непригоден (хеширование делит
// ключ на число корзин — деление на ноль), отрицательное число корзин
// бессмысленно. Некорректный размер — ошибка входа (ErrHashTableInvalidBuckets),
// а не паника: публичный библиотечный API получает размер от вызывающего
// кода и обязан отдать проблему управляемо — ошибкой, которую тот решает
// показать, залогировать или обернуть; panic вместо этого роняет всю
// программу и не оставляет вызывающему выбор.
func NewHashTable(nBuckets int) (*HashTable, error) {
	if nBuckets <= 0 {
		return nil, ErrHashTableInvalidBuckets
	}
	return &HashTable{buckets: make([]*hashEntry, nBuckets)}, nil
}

// Put добавляет пару «ключ — значение» или обновляет значение существующего
// ключа: повторный Put не растит таблицу — Len не меняется. Новая запись
// встаёт во главу цепочки своей корзины: O(1) от длины обхода выше, зато
// соседние записи никуда не сдвигаются. Записей с одним ключом в таблице
// не бывает — обновление заменяет старое значение.
func (h *HashTable) Put(key, value int) {
	idx := h.bucketOf(key)
	if _, cur := findEntry(h.buckets[idx], key); cur != nil {
		cur.value = value // ключ уже есть: переписываем значение, размер тот же
		return
	}
	// Новый ключ: вставка в голову цепочки — старая голова становится next.
	h.buckets[idx] = &hashEntry{key: key, value: value, next: h.buckets[idx]}
	h.size++
}

// Get возвращает значение по ключу и признак попадания. Промах — не ошибка:
// «ключа нет» — обычный результат поиска, второй флаг false. Значения в
// возвращаемом int при промахе нет смысла читать (стоит ноль).
func (h *HashTable) Get(key int) (int, bool) {
	idx := h.bucketOf(key)
	_, cur := findEntry(h.buckets[idx], key)
	if cur == nil {
		return 0, false // промах: ключа нет в цепочке корзины
	}
	return cur.value, true
}

// Delete удаляет ключ и возвращает признак удаления: true — запись была и
// удалена, false — промах (не ошибка). Удаление одной записи не должно
// повреждать остальные: связи перепрыгивают через удаляемую запись
// (prev.next = victim.next), сами записи на местах. Голова цепочки — особый
// случай: предыдущей записи нет, корзина начинает смотреть на следующий узел.
func (h *HashTable) Delete(key int) bool {
	idx := h.bucketOf(key)
	prev, victim := findEntry(h.buckets[idx], key)
	if victim == nil {
		return false // промах: ключа нет, удалять нечего
	}
	if prev == nil {
		h.buckets[idx] = victim.next // удаляем голову цепочки
	} else {
		prev.next = victim.next // перепрыгиваем удаляемую запись
	}
	h.size--
	return true
}

// Len возвращает число записей во всей таблице. Размер считается инкрементно
// при вставке и удалении, поэтому Len — O(1), обход корзин не нужен.
func (h *HashTable) Len() int {
	return h.size
}

// rawRemainder — сырой остаток ключа от деления на число корзин: знак
// остатка повторяет знак ключа, нормализации здесь нет. Единственный
// источник формулы остатка: bucketOf и события-эмиттеры берут её отсюда.
func (h *HashTable) rawRemainder(key int) int {
	return key % len(h.buckets)
}

// bucketOf — индекс корзины для целочисленного ключа: сырой остаток
// rawRemainder, нормализованный в диапазон 0..числоКорзин-1. У Go знак
// остатка повторяет знак ключа: ключ -4 при 5 корзинах даёт -4 — это вне
// диапазона индексов, поэтому отрицательный остаток нормализуем
// прибавлением числа корзин: -4 + 5 = 1.
func (h *HashTable) bucketOf(key int) int {
	idx := h.rawRemainder(key)
	if idx < 0 {
		idx += len(h.buckets)
	}
	return idx
}

// findEntry — небольшой помощник поиска по цепочке корзины: идёт от головы
// запись за записью и возвращает предыдущую запись (prev) и найденную
// (cur); prev == nil означает, что найденная запись — голова цепочки
// (это особый случай для Delete), оба nil — ключа в цепочке нет.
func findEntry(head *hashEntry, key int) (prev, cur *hashEntry) {
	for cur = head; cur != nil; cur = cur.next {
		if cur.key == key {
			return prev, cur
		}
		prev = cur
	}
	return nil, nil
}
