// Пакет frame — конверт кадра визуализации (ADR-0002).
//
// Транспорт (SSE-эндпоинт) знает только про Frame и не знает про
// конкретные алгоритмы: снимок структуры данных — свой тип у каждого
// Frame Renderer, поэтому новый алгоритм не требует правок транспорта.
package frame

// KindArray — кадры со снимком массива.
const KindArray = "array"

// Frame — самодостаточный снимок визуализации на один шаг (ADR-0002).
// Клиенту не нужно накапливать состояние: кадр содержит полную картину —
// снимок структуры, подсветки и пояснение, и отрисовывается как есть.
type Frame struct {
	Step        int    `json:"step"`        // порядковый номер шага, начиная с 1
	Kind        string `json:"kind"`        // тип структуры: "array", "tree", "graph"...
	Explanation string `json:"explanation"` // текст пояснения на русском
	Data        any    `json:"data"`        // снимок структуры данных (свой тип у каждого рендерера)
}
