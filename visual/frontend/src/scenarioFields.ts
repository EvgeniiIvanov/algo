// Поля строки сценария — общая токенизация всех парсеров сценариев фронта
// (стек, очередь, список, односвязный список, хеш-таблица, BST, Trie).
// Зеркало whitespace-семантики Go strings.Fields / unicode.IsSpace, которой
// держатся серверные парсеры: ASCII-пробелы ('\t', '\n', '\v', '\f', '\r',
// ' '), NEL U+0085, NBSP U+00A0 и Unicode-пробелы категорий Zs/Zl/Zp
// (U+1680, U+2000–U+200A, U+2028, U+2029, U+202F, U+205F, U+3000).
// Отступлений от JS \s ровно два, и они зафиксированы тестами: BOM U+FEFF
// в JS пробельный, а в Go — нет (иначе токен приклеился бы к BOM на
// сервере); NEL U+0085 в Go пробельный, а в JS — нет. Клиентская
// токенизация совпадает с серверной, чтобы ошибки ввода ловились до Run;
// сервер перепроверяет — он авторитетен.

/** Один run пробельных символов по unicode.IsSpace (см. шапку модуля). */
const WHITESPACE_RUN = new RegExp(
  "[\\t\\n\\v\\f\\r \\u0085\\u00A0\\u1680\\u2000-\\u200A\\u2028\\u2029\\u202F\\u205F\\u3000]+",
);

/**
 * Разобрать строку сценария на поля по whitespace-семантике strings.Fields:
 * соседние пробельные символы — один разделитель, пустые поля отбрасываются.
 * Пустая строка или строка только из пробелов даёт [].
 */
export function splitScenarioFields(line: string): string[] {
  return line.split(WHITESPACE_RUN).filter((field) => field.length > 0);
}
