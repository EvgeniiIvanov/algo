// Поля строки сценария — токенизация парсеров сценариев фронта.
// Два набора whitespace-семантики под разные швы:
//
// - splitScenarioFields — зеркало Go strings.Fields / unicode.IsSpace,
//   которой держится серверный парсер сценария Trie (visual/server/trie.go):
//   ASCII-пробелы ('\t', '\n', '\v', '\f', '\r', ' '), NEL U+0085, NBSP
//   U+00A0 и Unicode-пробелы категорий Zs/Zl/Zp (U+1680, U+2000–U+200A,
//   U+2028, U+2029, U+202F, U+205F, U+3000). Отступлений от JS \s ровно
//   два, и они зафиксированы тестами: BOM U+FEFF в JS пробельный, а в
//   Go — нет (иначе токен приклеился бы к BOM на сервере); NEL U+0085 в
//   Go пробельный, а в JS — нет. Клиентская токенизация Trie совпадает
//   с серверной, чтобы ошибки ввода ловились до Run; сервер перепроверяет
//   — он авторитетен.
//
// - splitLegacyScenarioFields — прежняя клиентская токенизация шести
//   исторических парсеров (стек, очередь, список, односвязный список,
//   хеш-таблица, BST): trim + разрез по JS \s. Их серверные парсеры
//   разобрали бы и Go-семантику, но наблюдаемое поведение фронта для
//   этих швов менять не стали (критерий тикета 42: прежние визуализации
//   работают без изменения поведения; см. ADR-0004); расхождения с Go —
//   BOM U+FEFF здесь пробельный, NEL U+0085 нет — остались как были
//   и зафиксированы тестами.

/** Один run пробельных символов по unicode.IsSpace (см. шапку модуля). */
const GO_WHITESPACE_RUN = new RegExp(
  "[\\t\\n\\v\\f\\r \\u0085\\u00A0\\u1680\\u2000-\\u200A\\u2028\\u2029\\u202F\\u205F\\u3000]+",
);

/**
 * Разобрать строку сценария на поля по whitespace-семантике strings.Fields
 * (Trie): соседние пробельные символы — один разделитель, пустые поля
 * отбрасываются. Пустая строка или строка только из пробелов даёт [].
 */
export function splitScenarioFields(line: string): string[] {
  return line.split(GO_WHITESPACE_RUN).filter((field) => field.length > 0);
}

/** Один run пробельных символов по JS \s (см. шапку модуля). */
const LEGACY_WHITESPACE_RUN = /\s+/;

/**
 * Прежняя токенизация строк исторических парсеров сценариев (стек,
 * очередь, список, односвязный список, хеш-таблица, BST): trim и разрез
 * по JS \s — соседние пробельные символы один разделитель, пустые поля
 * отбрасываются; пустая строка или строка только из пробелов даёт [].
 * Не менять под Go-паритет: шов держит прежнее наблюдаемое поведение
 * (см. шапку модуля и тесты).
 */
export function splitLegacyScenarioFields(line: string): string[] {
  return line
    .trim()
    .split(LEGACY_WHITESPACE_RUN)
    .filter((field) => field.length > 0);
}
