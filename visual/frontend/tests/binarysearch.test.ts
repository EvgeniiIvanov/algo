// Тест шва фронта (см. docs/SPEC.md, шов фронтенда):
// парсинг входа бинарного поиска (массив + target) — ошибки ввода
// ловим до Run. Зеркало серверного парсера (visual/server/server.go):
// формы 2.0 / 1e2 / 0x10, которые Number() съедает, отвергаются на
// клиенте понятной ошибкой, а не HTTP 400 после запроса.
// Граница значений — безопасное целое: за пределами rejected, не округляется.
import { describe, expect, it } from "vitest";
import { parseTarget, parseValues } from "../src/binarysearch";

describe("parseValues", () => {
  it("разбирает массив из целых чисел через запятую", () => {
    expect(parseValues("1,3,5,7,9")).toEqual([1, 3, 5, 7, 9]);
  });

  it("допускает пробелы вокруг чисел, как серверный TrimSpace", () => {
    expect(parseValues(" 1 , 2 , 3 ")).toEqual([1, 2, 3]);
  });

  it("принимает знаковые формы и ведущие нули, как Go strconv.Atoi", () => {
    expect(parseValues("+2,-2")).toEqual([2, -2]);
    expect(parseValues("007,+08")).toEqual([7, 8]);
  });

  it("принимает границу безопасного целого в обе стороны", () => {
    expect(parseValues("9007199254740991,-9007199254740991")).toEqual([
      9007199254740991,
      -9007199254740991,
    ]);
  });

  it("отклоняет пустой ввод", () => {
    expect(() => parseValues("")).toThrow(/введите массив/);
    expect(() => parseValues("   ")).toThrow(/введите массив/);
  });

  it("отклоняет пустой компонент между запятыми и хвостовую запятую", () => {
    expect(() => parseValues("1,,3")).toThrow(/не удалось разобрать «» как целое число/);
    expect(() => parseValues("1,2,")).toThrow(/не удалось разобрать «» как целое число/);
  });

  it("отклоняет дробные и нечисловой мусор", () => {
    expect(() => parseValues("1,2.5,3")).toThrow(/не удалось разобрать «2\.5» как целое число/);
    expect(() => parseValues("три")).toThrow(/не удалось разобрать «три» как целое число/);
  });

  it("отклоняет формы 2.0, 1e2, 0x10 — их отвергнет и серверный Atoi", () => {
    expect(() => parseValues("2.0")).toThrow(/не удалось разобрать «2\.0» как целое число/);
    expect(() => parseValues("1e2")).toThrow(/не удалось разобрать «1e2» как целое число/);
    expect(() => parseValues("0x10")).toThrow(/не удалось разобрать «0x10» как целое число/);
  });

  it("отклоняет значения за пределами безопасного целого: не округляет молча", () => {
    expect(() => parseValues("9007199254740992")).toThrow(/пределами точного диапазона/);
    expect(() => parseValues("-9007199254740992")).toThrow(/пределами точного диапазона/);
    // Границы формально грамматически верны: ошибка именно про диапазон,
    // а не «не целое».
    expect(() => parseValues("99999999999999999999")).toThrow(/пределами точного диапазона/);
  });
});

describe("parseTarget", () => {
  it("разбирает простые, знаковые и ведущие нули, как Go strconv.Atoi", () => {
    expect(parseTarget("7")).toBe(7);
    expect(parseTarget("+2")).toBe(2);
    expect(parseTarget("-3")).toBe(-3);
    expect(parseTarget("007")).toBe(7);
    expect(parseTarget(" 12 ")).toBe(12);
  });

  it("принимает границу безопасного целого в обе стороны", () => {
    expect(parseTarget("9007199254740991")).toBe(9007199254740991);
    expect(parseTarget("-9007199254740991")).toBe(-9007199254740991);
  });

  it("отклоняет пустой ввод", () => {
    expect(() => parseTarget("")).toThrow(/введите искомое значение/);
    expect(() => parseTarget("   ")).toThrow(/введите искомое значение/);
  });

  it("отклоняет формы 2.0, 1e2, 0x10 и дробные", () => {
    expect(() => parseTarget("2.0")).toThrow(/не удалось разобрать «2\.0» как целое число/);
    expect(() => parseTarget("1e2")).toThrow(/не удалось разобрать «1e2» как целое число/);
    expect(() => parseTarget("0x10")).toThrow(/не удалось разобрать «0x10» как целое число/);
    expect(() => parseTarget("2.5")).toThrow(/не удалось разобрать «2\.5» как целое число/);
  });

  it("отклоняет значения за пределами безопасного целого: не округляет молча", () => {
    expect(() => parseTarget("9007199254740992")).toThrow(/пределами точного диапазона/);
    expect(() => parseTarget("-9007199254740992")).toThrow(/пределами точного диапазона/);
  });
});
